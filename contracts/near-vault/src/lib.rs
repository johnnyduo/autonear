// ------------------------------------------------------------------ pure helpers

pub fn to_hex(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push(HEX[(b >> 4) as usize] as char);
        s.push(HEX[(b & 15) as usize] as char);
    }
    s
}

/// Strict parser: exactly 64 lowercase hex characters.
pub fn parse_hex32(s: &str) -> Option<[u8; 32]> {
    let b = s.as_bytes();
    if b.len() != 64 {
        return None;
    }
    let nib = |c: u8| match c {
        b'0'..=b'9' => Some(c - b'0'),
        b'a'..=b'f' => Some(c - b'a' + 10),
        _ => None,
    };
    let mut out = [0u8; 32];
    for i in 0..32 {
        out[i] = (nib(b[2 * i])? << 4) | nib(b[2 * i + 1])?;
    }
    Some(out)
}

/// Sub-account label rule: `1..=32` bytes of `[a-z0-9_-]`, first and last char alphanumeric,
/// no two separators in a row (NEAR account-id grammar), and no dots (one level only).
pub fn valid_name(name: &str) -> bool {
    let b = name.as_bytes();
    let sep = |c: u8| c == b'-' || c == b'_';
    !b.is_empty()
        && (MIN_NAME_LEN..=MAX_NAME_LEN).contains(&b.len())
        && b.iter()
            .all(|&c| c.is_ascii_lowercase() || c.is_ascii_digit() || sep(c))
        && !sep(b[0])
        && !sep(b[b.len() - 1])
        && !b.windows(2).any(|w| sep(w[0]) && sep(w[1]))
}

/// NEAR analogues of the zero address: `system` and the all-zero implicit account.
fn is_zero_account(s: &str) -> bool {
    s == "system" || s == "0".repeat(64)
}

/// Spend budget check shared by draw and deploy. `period_spent_now` is already period-adjusted.
fn check_spend(
    m: &Mandate,
    usage: &Usage,
    period_spent_now: u128,
    amount: u128,
    available: u128,
) -> Result<(), Fail> {
    if period_spent_now.saturating_add(amount) > m.period_cap {
        return Err(fail(Code::PeriodCap, "period cap exceeded"));
    }
    if usage.total_spent.saturating_add(amount) > m.total_cap {
        return Err(fail(Code::TotalCap, "total cap exceeded"));
    }
    if amount > available {
        return Err(fail(Code::InsufficientBalance, "amount exceeds available"));
    }
    Ok(())
}

fn now_secs() -> u64 {
    env::block_timestamp() / NS_PER_SEC
}

fn token(yocto: u128) -> NearToken {
    NearToken::from_yoctonear(yocto)
}

/// The ONLY way value leaves the vault besides the deploy batch: one `Transfer` action to `to`.
/// Promises are built with the raw `env::promise_batch_*` calls on purpose: the `near_sdk::Promise`
/// type links every action kind (add_key, delete_key, delete_account, stake) into the wasm; this way
/// the wasm imports exactly the host functions used (checked by `wasm-tools`, see README).
fn send(to: &AccountId, yocto: u128) {
    let p = env::promise_batch_create(to);
    env::promise_batch_action_transfer(p, token(yocto));
    env::promise_return(p);
}

// -------------------------------------------------------------------- contract

#[near]
impl Vault {
    #[init]
    pub fn new(owner: AccountId, network_id: String) -> Self {
        require!(!env::state_exists(), "already initialized");
        require!(
            !network_id.is_empty() && network_id.len() <= MAX_NETWORK_ID_LEN,
            "invalid network_id"
        );
        if is_zero_account(owner.as_str()) || owner == env::current_account_id() {
            fail(Code::BadOwner, "invalid owner").abort();
        }
        Event::Initialized {
            owner: owner.clone(),
            network_id: network_id.clone(),
        }
        .emit();
        Self {
            owner,
            pending_owner: None,
            paused: false,
            network_id,
            epoch: 0,
            mandate: None,
            usage: Usage::default(),
            templates: IterableMap::new(StorageKey::Templates),
            used_names: LookupSet::new(StorageKey::UsedNames),
        }
    }

    // ------------------------------------------------------------ owner ops

    /// Replaces any mandate (also a revoked/expired one), resets usage, `epoch += 1`, `start = now`.
    /// `agent` is a string so an empty/invalid value reverts with `E_BadMandate` (not a decode error).
    pub fn set_mandate(
        &mut self,
        agent: String,
        expires_at: U64,
        per_draw_cap: U128,
        period_secs: U64,
        period_cap: U128,
        total_cap: U128,
        max_deploys: u32,
    ) {
        let by = or_abort(self.assert_owner());
        let now = now_secs();
        let agent = or_abort(self.parse_agent(&agent));
        let ok = expires_at.0 > now
            && expires_at.0 <= now.saturating_add(MAX_MANDATE_SECS)
            && per_draw_cap.0 > 0
            && per_draw_cap.0 <= period_cap.0
            && period_cap.0 <= total_cap.0
            && (MIN_PERIOD_SECS..=MAX_PERIOD_SECS).contains(&period_secs.0)
            && max_deploys <= MAX_DEPLOYS;
        if !ok {
            fail(Code::BadMandate, "mandate parameters out of bounds").abort();
        }
        self.epoch += 1;
        self.usage = Usage::default();
        self.mandate = Some(Mandate {
            agent: agent.clone(),
            expires_at: expires_at.0,
            per_draw_cap: per_draw_cap.0,
            period_secs: period_secs.0,
            period_cap: period_cap.0,
            total_cap: total_cap.0,
            max_deploys,
            revoked: false,
            start: now,
        });
        Event::MandateSet {
            agent,
            epoch: U64(self.epoch),
            start: U64(now),
            expires_at,
            per_draw_cap,
            period_secs,
            period_cap,
            total_cap,
            max_deploys,
            by,
        }
        .emit();
    }

    /// Idempotent; no mandate => `E_NoMandate`. Only the first call (a state change) emits an event.
    pub fn revoke(&mut self) {
        let by = or_abort(self.assert_owner());
        let epoch = self.epoch;
        let m = self
            .mandate
            .as_mut()
            .unwrap_or_else(|| fail(Code::NoMandate, "no mandate").abort());
        if !m.revoked {
            m.revoked = true;
            Event::MandateRevoked {
                agent: m.agent.clone(),
                epoch: U64(epoch),
                by,
            }
            .emit();
        }
    }

    /// Blocks agent operations only. Idempotent (an event only on change).
    pub fn pause(&mut self) {
        let by = or_abort(self.assert_owner());
        if !self.paused {
            self.paused = true;
            Event::Paused { by }.emit();
        }
    }

    pub fn unpause(&mut self) {
        let by = or_abort(self.assert_owner());
        if self.paused {
            self.paused = false;
            Event::Unpaused { by }.emit();
        }
    }

    /// `template_id` = sha256(wasm) as 64 lowercase hex. `init_args` (a JSON object, stored compact,
    /// <= 1 KiB, default `{}`) and `init_gas` (5..=200 Tgas, default 30 Tgas) are fixed here by the
    /// owner; the agent never supplies them. `deposit` = yoctoNEAR forwarded to the new sub-account.
    /// Re-allowing an existing id updates it.
    pub fn allow_template(
        &mut self,
        template_id: String,
        label: String,
        deposit: U128,
        init_args: Option<Value>,
        init_gas: Option<U64>,
    ) {
        let by = or_abort(self.assert_owner());
        let id = parse_hex32(&template_id)
            .unwrap_or_else(|| fail(Code::BadTemplate, "template id must be 64 hex chars").abort());
        if label.len() > MAX_LABEL_BYTES {
            fail(Code::BadTemplate, "label longer than 64 bytes").abort();
        }
        let args = init_args.unwrap_or_else(|| Value::Object(serde_json::Map::new()));
        if !args.is_object() {
            fail(Code::BadTemplate, "init_args must be a JSON object").abort();
        }
        let args_bytes = serde_json::to_vec(&args)
            .unwrap_or_else(|_| fail(Code::BadTemplate, "init_args not serializable").abort());
        if args_bytes.len() > MAX_INIT_ARGS_BYTES {
            fail(Code::BadTemplate, "init_args longer than 1 KiB").abort();
        }
        let gas = init_gas.map_or(DEFAULT_INIT_GAS, |g| g.0);
        if !(MIN_INIT_GAS..=MAX_INIT_GAS).contains(&gas) {
            fail(Code::BadTemplate, "init_gas outside 5..=200 Tgas").abort();
        }
        let updated = self
            .templates
            .insert(
                id,
                Template {
                    label: label.clone(),
                    deposit: deposit.0,
                    init_args: args_bytes,
                    init_gas: gas,
                },
            )
            .is_some();
        Event::TemplateAllowed {
            template: template_id,
            label,
            deposit,
            init_gas: U64(gas),
            init_args: args,
            updated,
            by,
        }
        .emit();
    }

    pub fn disallow_template(&mut self, template_id: String) {
        let by = or_abort(self.assert_owner());
        let removed = parse_hex32(&template_id).and_then(|id| self.templates.remove(&id));
        if removed.is_none() {
            fail(Code::TemplateNotAllowed, "unknown template").abort();
        }
        Event::TemplateDisallowed {
            template: template_id,
            by,
        }
        .emit();
    }

    /// Sends to the owner only. Works while paused, revoked or expired.
    pub fn withdraw(&mut self, amount: U128) {
        let owner = or_abort(self.assert_owner());
        if amount.0 == 0 {
            fail(Code::BadAmount, "amount must be > 0").abort();
        }
        if amount.0 > Self::available_yocto() {
            fail(Code::InsufficientBalance, "amount exceeds available").abort();
        }
        Event::Withdrawn {
            to: owner.clone(),
            amount,
        }
        .emit();
        send(&owner, amount.0);
    }

    /// Step 1 of the two-step transfer. Empty/zero/self/vault => `E_BadOwner`.
    pub fn transfer_ownership(&mut self, to: String) {
        let owner = or_abort(self.assert_owner());
        let new_owner = to
            .parse::<AccountId>()
            .ok()
            .filter(|a| {
                !is_zero_account(a.as_str()) && *a != owner && *a != env::current_account_id()
            })
            .unwrap_or_else(|| fail(Code::BadOwner, "invalid new owner").abort());
        self.pending_owner = Some(new_owner.clone());
        Event::OwnershipTransferStarted {
            owner,
            pending: new_owner,
        }
        .emit();
    }

    /// Step 2: only the pending owner (anyone else, or no pending owner => `E_Unauthorized`).
    pub fn accept_ownership(&mut self) {
        let caller = env::predecessor_account_id();
        if self.pending_owner.as_ref() != Some(&caller) {
            fail(Code::Unauthorized, "only the pending owner").abort();
        }
        let old = std::mem::replace(&mut self.owner, caller.clone());
        self.pending_owner = None;
        Event::OwnershipTransferred { old, new: caller }.emit();
    }

    // ------------------------------------------------------------ anyone

    /// Gift. A plain transfer to the account also works but emits no event.
    #[payable]
    pub fn deposit(&mut self) {
        let amount = env::attached_deposit().as_yoctonear();
        if amount == 0 {
            fail(Code::BadAmount, "attach a deposit").abort();
        }
        Event::Deposited {
            from: env::predecessor_account_id(),
            amount: U128(amount),
        }
        .emit();
    }

    // ------------------------------------------------------------ agent ops

    /// Pull `amount` yoctoNEAR to `mandate.agent` (never to anyone else). Counters are updated
    /// before the transfer promise is created (optimistic); if the transfer fails (e.g. the agent
    /// account was deleted) the runtime refunds the vault and `on_drawn` reverses the charge.
    pub fn draw(&mut self, amount: U128) {
        let caller = env::predecessor_account_id();
        let now = now_secs();
        let agent = or_abort(self.plan_draw(&caller, amount.0, now, Self::available_yocto()));
        self.apply_spend(now, amount.0);
        Event::Drawn {
            agent: agent.clone(),
            amount,
            epoch: U64(self.epoch),
            total_spent: U128(self.usage.total_spent),
            period_spent: U128(self.usage.period_spent),
        }
        .emit();
        let transfer = env::promise_batch_create(&agent);
        env::promise_batch_action_transfer(transfer, token(amount.0));
        let callback = env::promise_batch_then(transfer, &env::current_account_id());
        let cb_args = serde_json::to_vec(&serde_json::json!({
            "epoch": U64(self.epoch),
            "period_index": U64(self.usage.period_index),
            "agent": agent,
            "amount": amount,
        }))
        .unwrap_or_else(|_| env::panic_str("callback args"));
        env::promise_batch_action_function_call(
            callback,
            "on_drawn",
            &cb_args,
            token(0),
            Gas::from_gas(DRAW_CALLBACK_GAS),
        );
        env::promise_return(callback);
    }

    /// Callback of `draw`. If the transfer failed, the amount has been refunded to the vault and the
    /// optimistic charge is reversed: always inside the same mandate epoch (a newer mandate has its
    /// own counters and is left alone), `period_spent` only if the stored period is still the one
    /// charged. Saturating, so a replay can never underflow. On success it does nothing.
    #[private]
    pub fn on_drawn(&mut self, epoch: U64, period_index: U64, agent: AccountId, amount: U128) {
        require!(
            env::promise_results_count() == 1,
            "expected one promise result"
        );
        if let PromiseResult::Failed = env::promise_result(0) {
            let reversed = epoch.0 == self.epoch;
            if reversed {
                self.usage.total_spent = self.usage.total_spent.saturating_sub(amount.0);
                if self.usage.period_index == period_index.0 {
                    self.usage.period_spent = self.usage.period_spent.saturating_sub(amount.0);
                }
            }
            Event::DrawFailed {
                agent,
                amount,
                epoch,
                reversed,
            }
            .emit();
        }
    }

    /// Creates `{name}.{vault}`, funds it with the template deposit, deploys `code` and calls
    /// `new(<stored init_args>)` in ONE batch with no `AddKey` (the sub-account is keyless and
    /// immutable). `sha256(code)` must equal `template`. The charge is optimistic; `on_deployed`
    /// reverses it if the batch fails. Pass ~300 Tgas: gas is the agent's, not the vault's.
    pub fn deploy(&mut self, template: String, name: String, code: Base64VecU8) {
        let caller = env::predecessor_account_id();
        let now = now_secs();
        let code: Vec<u8> = code.into();
        let plan = or_abort(self.plan_deploy(
            &caller,
            &template,
            &name,
            Some(&code),
            now,
            Self::available_yocto(),
        ));
        // Effects first (counters + name reservation), then the promise.
        self.apply_spend(now, plan.template.deposit);
        self.usage.deploys += 1;
        self.used_names.insert(name.clone());
        let period_index = self.usage.period_index;
        Event::Deployed {
            agent: caller,
            template: template.clone(),
            name: name.clone(),
            target: plan.target.clone(),
            deposit: U128(plan.template.deposit),
            epoch: U64(self.epoch),
            deploys: self.usage.deploys,
            total_spent: U128(self.usage.total_spent),
            period_spent: U128(self.usage.period_spent),
        }
        .emit();
        // Deliberately NO add_key action: the sub-account has no access key at all.
        let batch = env::promise_batch_create(&plan.target);
        env::promise_batch_action_create_account(batch);
        env::promise_batch_action_transfer(batch, token(plan.template.deposit));
        env::promise_batch_action_deploy_contract(batch, &code);
        env::promise_batch_action_function_call(
            batch,
            "new",
            &plan.template.init_args,
            token(0),
            Gas::from_gas(plan.template.init_gas),
        );
        let callback = env::promise_batch_then(batch, &env::current_account_id());
        let cb_args = serde_json::to_vec(&serde_json::json!({
            "epoch": U64(self.epoch),
            "period_index": U64(period_index),
            "template": template,
            "name": name,
            "deposit": U128(plan.template.deposit),
        }))
        .unwrap_or_else(|_| env::panic_str("callback args"));
        env::promise_batch_action_function_call(
            callback,
            "on_deployed",
            &cb_args,
            token(0),
            Gas::from_gas(CALLBACK_GAS),
        );
        env::promise_return(callback);
    }

    /// Callback of `deploy`. If the batch failed, the deposit has been refunded to the vault and
    /// the optimistic charge is reversed (only inside the same mandate epoch; a newer mandate has
    /// its own counters and is left alone) and the name is released.
    #[private]
    pub fn on_deployed(
        &mut self,
        epoch: U64,
        period_index: U64,
        template: String,
        name: String,
        deposit: U128,
    ) {
        require!(
            env::promise_results_count() == 1,
            "expected one promise result"
        );
        let target = self.sub_account(&name);
        match env::promise_result(0) {
            PromiseResult::Successful(_) => {
                Event::DeployConfirmed {
                    template,
                    name,
                    target,
                }
                .emit();
            }
            PromiseResult::Failed => {
                self.used_names.remove(&name);
                let reversed = epoch.0 == self.epoch;
                if reversed {
                    self.usage.total_spent = self.usage.total_spent.saturating_sub(deposit.0);
                    self.usage.deploys = self.usage.deploys.saturating_sub(1);
                    if self.usage.period_index == period_index.0 {
                        self.usage.period_spent = self.usage.period_spent.saturating_sub(deposit.0);
                    }
                }
                Event::DeployFailed {
                    template,
                    name,
                    target,
                    deposit,
                    epoch,
                    reversed,
                }
                .emit();
            }
        }
    }

    // ------------------------------------------------------------ views

    pub fn config(&self) -> ConfigView {
        ConfigView {
            owner: self.owner.clone(),
            pending_owner: self.pending_owner.clone(),
            paused: self.paused,
            network_id: self.network_id.clone(),
            epoch: U64(self.epoch),
            vault_id: env::current_account_id(),
            version: EVENT_STANDARD_VERSION.to_string(),
            reserve: U128(RESERVE_YOCTO),
        }
    }

    pub fn mandate(&self) -> Option<MandateView> {
        let now = now_secs();
        self.mandate.as_ref().map(|m| MandateView {
            agent: m.agent.clone(),
            expires_at: U64(m.expires_at),
            per_draw_cap: U128(m.per_draw_cap),
            period_secs: U64(m.period_secs),
            period_cap: U128(m.period_cap),
            total_cap: U128(m.total_cap),
            max_deploys: m.max_deploys,
            revoked: m.revoked,
            start: U64(m.start),
            active: !m.revoked && now < m.expires_at,
        })
    }

    pub fn usage(&self) -> UsageView {
        UsageView {
            total_spent: U128(self.usage.total_spent),
            period_index: U64(self.usage.period_index),
            period_spent: U128(self.usage.period_spent),
            deploys: self.usage.deploys,
        }
    }

    pub fn template(&self, template_id: String) -> Option<TemplateView> {
        let id = parse_hex32(&template_id)?;
        self.templates.get(&id).map(|t| Self::template_view(&id, t))
    }

    /// Allowlisted templates, 50 per page by default, at most 100. Order is insertion order until a
    /// `disallow_template` moves the last entry into the freed slot.
    pub fn templates(&self, from_index: Option<U64>, limit: Option<U64>) -> Vec<TemplateView> {
        let from = usize::try_from(from_index.map_or(0, |v| v.0)).unwrap_or(usize::MAX);
        let limit = usize::try_from(limit.map_or(DEFAULT_PAGE, |v| v.0).min(MAX_PAGE)).unwrap_or(0);
        self.templates
            .iter()
            .skip(from)
            .take(limit)
            .map(|(id, t)| Self::template_view(id, t))
            .collect()
    }

    /// `account_balance - storage_usage * byte_cost - 1 NEAR`, floored at 0.
    pub fn available(&self) -> U128 {
        U128(Self::available_yocto())
    }

    /// Budget figures effective at `now` (seconds; default: current block time). `None` without a mandate.
    pub fn period_state(&self, now: Option<U64>) -> Option<PeriodStateView> {
        let now = now.map_or_else(now_secs, |n| n.0);
        let m = self.mandate.as_ref()?;
        let idx = Self::period_index(m, now);
        let spent = self.period_spent_at(idx);
        Some(PeriodStateView {
            period_index: U64(idx),
            period_start: U64(m.start.saturating_add(idx.saturating_mul(m.period_secs))),
            period_end: U64(m
                .start
                .saturating_add(idx.saturating_add(1).saturating_mul(m.period_secs))),
            period_spent: U128(spent),
            period_remaining: U128(m.period_cap.saturating_sub(spent)),
            total_spent: U128(self.usage.total_spent),
            total_remaining: U128(m.total_cap.saturating_sub(self.usage.total_spent)),
            deploys: self.usage.deploys,
            deploys_remaining: m.max_deploys.saturating_sub(self.usage.deploys),
            active: !m.revoked && now < m.expires_at,
        })
    }

    /// The error code `draw(amount)` would hit now if called by the bound agent; "" = ok.
    pub fn preview_draw(&self, amount: U128) -> String {
        let caller = self.assumed_agent();
        match self.plan_draw(&caller, amount.0, now_secs(), Self::available_yocto()) {
            Ok(_) => String::new(),
            Err(f) => f.code.as_str().to_string(),
        }
    }

    /// The error code `deploy(template, name, <matching code>)` would hit now if called by the bound
    /// agent; "" = ok. The wasm bytes are not part of the preview, so `CodeMismatch` is never returned
    /// (it is checked with the real bytes in `deploy`).
    pub fn preview_deploy(&self, template: String, name: String) -> String {
        let caller = self.assumed_agent();
        match self.plan_deploy(
            &caller,
            &template,
            &name,
            None,
            now_secs(),
            Self::available_yocto(),
        ) {
            Ok(_) => String::new(),
            Err(f) => f.code.as_str().to_string(),
        }
    }
}

/// Everything `deploy` needs once the rules passed.
struct DeployPlan {
    template: Template,
    target: AccountId,
}

impl Vault {
    fn assert_owner(&self) -> Result<AccountId, Fail> {
        let caller = env::predecessor_account_id();
        if caller == self.owner {
            Ok(caller)
        } else {
            Err(fail(Code::Unauthorized, "only the owner"))
        }
    }

    /// The caller a preview assumes: the bound agent (any account when there is no mandate: the
    /// NoMandate rule is caller independent).
    fn assumed_agent(&self) -> AccountId {
        self.mandate
            .as_ref()
            .map_or_else(env::predecessor_account_id, |m| m.agent.clone())
    }

    fn parse_agent(&self, agent: &str) -> Result<AccountId, Fail> {
        agent
            .parse::<AccountId>()
            .ok()
            .filter(|a| !is_zero_account(a.as_str()) && *a != env::current_account_id())
            .ok_or_else(|| fail(Code::BadMandate, "invalid agent account"))
    }

    fn available_yocto() -> u128 {
        let storage_cost = u128::from(env::storage_usage())
            .saturating_mul(env::storage_byte_cost().as_yoctonear());
        env::account_balance()
            .as_yoctonear()
            .saturating_sub(storage_cost)
            .saturating_sub(RESERVE_YOCTO)
    }

    fn period_index(m: &Mandate, now: u64) -> u64 {
        now.saturating_sub(m.start) / m.period_secs
    }

    fn period_spent_at(&self, idx: u64) -> u128 {
        if self.usage.period_index == idx {
            self.usage.period_spent
        } else {
            0
        }
    }

    /// Common agent gate: NoMandate -> Unauthorized -> Paused -> MandateInactive.
    fn gate(&self, caller: &AccountId, now: u64) -> Result<&Mandate, Fail> {
        let m = self
            .mandate
            .as_ref()
            .ok_or_else(|| fail(Code::NoMandate, "no mandate"))?;
        if *caller != m.agent {
            return Err(fail(Code::Unauthorized, "caller is not the bound agent"));
        }
        if self.paused {
            return Err(fail(Code::Paused, "vault is paused"));
        }
        if m.revoked || now >= m.expires_at {
            return Err(fail(Code::MandateInactive, "mandate revoked or expired"));
        }
        Ok(m)
    }

    /// All `draw` rules, in spec order. Returns the recipient (always `mandate.agent`).
    fn plan_draw(
        &self,
        caller: &AccountId,
        amount: u128,
        now: u64,
        available: u128,
    ) -> Result<AccountId, Fail> {
        let m = self.gate(caller, now)?;
        if amount == 0 {
            return Err(fail(Code::BadAmount, "amount must be > 0"));
        }
        if amount > m.per_draw_cap {
            return Err(fail(Code::PerDrawCap, "per-draw cap exceeded"));
        }
        let idx = Self::period_index(m, now);
        check_spend(m, &self.usage, self.period_spent_at(idx), amount, available)?;
        Ok(m.agent.clone())
    }

    /// All `deploy` rules, in spec order. `code = None` skips only the `CodeMismatch` check.
    fn plan_deploy(
        &self,
        caller: &AccountId,
        template: &str,
        name: &str,
        code: Option<&[u8]>,
        now: u64,
        available: u128,
    ) -> Result<DeployPlan, Fail> {
        let m = self.gate(caller, now)?;
        let id = parse_hex32(template)
            .ok_or_else(|| fail(Code::TemplateNotAllowed, "template not allowlisted"))?;
        let t = self
            .templates
            .get(&id)
            .ok_or_else(|| fail(Code::TemplateNotAllowed, "template not allowlisted"))?;
        if let Some(code) = code {
            if env::sha256_array(code) != id {
                return Err(fail(Code::CodeMismatch, "sha256(code) != template id"));
            }
        }
        if self.usage.deploys >= m.max_deploys {
            return Err(fail(Code::DeployLimit, "deploy limit reached"));
        }
        let idx = Self::period_index(m, now);
        check_spend(
            m,
            &self.usage,
            self.period_spent_at(idx),
            t.deposit,
            available,
        )?;
        if self.used_names.contains(name) {
            return Err(fail(Code::AddressTaken, "sub-account name already used"));
        }
        if !valid_name(name) {
            return Err(fail(Code::BadName, "invalid sub-account name"));
        }
        let target = format!("{}.{}", name, env::current_account_id())
            .parse::<AccountId>()
            .map_err(|_| fail(Code::BadName, "sub-account id is not a valid account id"))?;
        Ok(DeployPlan {
            template: t.clone(),
            target,
        })
    }

    /// Re-bases the period if needed, then charges `amount` to both counters.
    fn apply_spend(&mut self, now: u64, amount: u128) {
        let m = self
            .mandate
            .as_ref()
            .unwrap_or_else(|| env::panic_str("no mandate"));
        let idx = Self::period_index(m, now);
        if self.usage.period_index != idx {
            self.usage.period_index = idx;
            self.usage.period_spent = 0;
        }
        self.usage.period_spent += amount;
        self.usage.total_spent += amount;
    }

    fn sub_account(&self, name: &str) -> AccountId {
        format!("{}.{}", name, env::current_account_id())
            .parse::<AccountId>()
            .unwrap_or_else(|_| env::panic_str("invalid sub-account id"))
    }

    fn template_view(id: &[u8; 32], t: &Template) -> TemplateView {
        TemplateView {
            id: to_hex(id),
            label: t.label.clone(),
            deposit: U128(t.deposit),
            init_args: serde_json::from_slice(&t.init_args).unwrap_or(Value::Null),
            init_gas: U64(t.init_gas),
        }
    }
}

